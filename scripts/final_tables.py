"""Tables of the final evaluation from paper/results/final_<map>_l<level>.jsonl.

    python scripts/final_tables.py            # writes paper/results/summary.md, table_levels.tex, table_types.tex

Rules: 'accepted' counts the model's own submissions only; assisted runs (system-built world, tier 'assisted') are listed in a separate column.
Intervals are Wilson 95%. Paired sign tests are per prompt id (repetitions summed), two-sided, exact.
"""
from __future__ import annotations

import collections
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RES = ROOT / "paper" / "results"
MAPS = ["paris_center", "munich"]
LEVELS = ["0", "1", "2"]
TYPE_INFO = {
    "ptp_env": ("Point to point, environment", "Walk to a landmark (bus stop, bench, waste basket)."),
    "ptp_road": ("Point to point, road", "Walk onto the road or to a spot on it."),
    "cpath": ("Constrained path", "Stay inside a corridor or keep to a path while walking."),
    "env_con": ("Environment constraint", "Reach a goal while keeping clear of a static obstacle."),
    "dyn_nav": ("Dynamic navigation", "Cross or walk while avoiding a moving vehicle or walker."),
    "dep_comp": ("Dependent composition", "Several tasks that must be done in a given order."),
    "indep_comp": ("Independent composition", "Several tasks that can be done in any order."),
    "mixed": ("Mixed", "Signal, order and traffic rules combined."),
}


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n == 0:
        return 0.0, 0.0
    p = k / n
    d = 1 + z * z / n
    c = p + z * z / (2 * n)
    h = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n))
    return (c - h) / d, (c + h) / d


def sign_test(a: dict, b: dict) -> tuple[int, int, int, float]:
    ids = set(a) | set(b)
    w = sum(a.get(i, 0) > b.get(i, 0) for i in ids)
    l = sum(a.get(i, 0) < b.get(i, 0) for i in ids)
    n = w + l
    if n == 0:
        return w, l, len(ids), 1.0
    p = min(1.0, 2 * sum(math.comb(n, k) for k in range(0, min(w, l) + 1)) / 2 ** n)
    return w, l, len(ids) - n, round(p, 3)


def load() -> dict[tuple[str, str], list[dict]]:
    out: dict[tuple[str, str], list[dict]] = {}
    for m in MAPS:
        for lv in LEVELS:
            f = RES / f"final_{m}_l{lv}.jsonl"
            if not f.exists():
                continue
            rows = [json.loads(x) for x in f.read_text(encoding="utf-8").splitlines() if x.strip()]
            out[(m, lv)] = [r for r in rows if str(r.get("level")) == lv]
    return out


def counts(rs: list[dict]) -> dict:
    n = len(rs)
    acc = sum(bool(r["accepted"]) for r in rs)
    asst = sum(1 for r in rs if not r["accepted"] and r.get("valid_output") and r.get("tier") == "assisted")
    return {"n": n, "acc": acc, "assisted": asst, "first": sum(bool(r["first_try"]) for r in rs),
            "adh": sum(bool(r["adherent"]) for r in rs), "acc_adh": sum(bool(r["accepted"] and r["adherent"]) for r in rs),
            "att": sum(r.get("attempts", 0) for r in rs if r["accepted"]) / max(1, acc)}


def pct(k: int, n: int) -> str:
    lo, hi = wilson(k, n)
    return f"{k}/{n} ({100 * k / n:.0f}%, {100 * lo:.0f}-{100 * hi:.0f})" if n else "-"


def main() -> None:
    data = load()
    md = ["# Final results (generated by scripts/final_tables.py)\n"]
    tex_lv = [r"\begin{tabular}{llrrrrr}", r"\toprule",
              r"Map & Level & Runs & Accepted (model only) & Assisted & First try & Adherent\\", r"\midrule"]
    md.append("## Levels\n\n| map | level | runs | accepted (model only) | assisted | first try | adherent (of runs) | mean script attempts when accepted |\n|---|---|---|---|---|---|---|---|")
    for m in MAPS + ["both"]:
        for lv in LEVELS:
            rs = data.get((m, lv), []) if m != "both" else sum([data.get((x, lv), []) for x in MAPS], [])
            if not rs:
                continue
            c = counts(rs)
            md.append(f"| {m} | L{lv} | {c['n']} | {pct(c['acc'], c['n'])} | {c['assisted']} | {c['first']} | {c['adh']} | {c['att']:.1f} |")
            lo, hi = wilson(c["acc"], c["n"])
            tex_lv.append(f"{m.replace('_', ' ')} & L{lv} & {c['n']} & {c['acc']} ({100 * c['acc'] / c['n']:.0f}\\%) & {c['assisted']} & {c['first']} & {c['adh']}\\\\")
        if m != "both":
            tex_lv.append(r"\midrule" if m != MAPS[-1] else r"\bottomrule")
    tex_lv.append(r"\end{tabular}")
    (RES / "table_levels.tex").write_text("\n".join(tex_lv) + "\n", encoding="utf-8")

    md.append("\n## Paired sign tests on 'accepted' (per prompt, both maps; wins of A, wins of B, ties, p)\n")
    per = {lv: collections.Counter() for lv in LEVELS}
    for (m, lv), rs in data.items():
        for r in rs:
            per[lv][r["id"]] += bool(r["accepted"])
    for a, b in (("1", "2"), ("0", "2"), ("0", "1")):
        if per[a] and per[b]:
            w, l, t, p = sign_test(per[a], per[b])
            md.append(f"* L{a} vs L{b}: {w}, {l}, {t}, p = {p}")

    md.append("\n## Per type at L2 (both maps pooled)\n")
    rs2 = sum([data.get((m, "2"), []) for m in MAPS], [])
    tex = [r"\begin{longtable}{p{2.6cm}p{5.2cm}p{3.4cm}p{3.2cm}}", r"\toprule",
           r"Scenario type & Task description & Metric & Result\\", r"\midrule", r"\endhead"]
    md.append("| type | runs | accepted (model only) | assisted | first try | adherent |\n|---|---|---|---|---|---|")
    for t, (name, desc) in TYPE_INFO.items():
        rs = [r for r in rs2 if r["type"] == t]
        if not rs:
            continue
        c = counts(rs)
        md.append(f"| {t} | {c['n']} | {pct(c['acc'], c['n'])} | {c['assisted']} | {c['first']} | {c['adh']} |")
        tex.append(f"{name} & {desc} & Accepted, model only & {c['acc']}/{c['n']}\\\\")
        tex.append(f" & & Assisted (system-built world) & {c['assisted']}\\\\")
        tex.append(f" & & First try & {c['first']}/{c['n']}\\\\")
        tex.append(f" & & Adherent to the request & {c['adh']}/{c['n']}\\\\ \\midrule")
    tex += [r"\bottomrule", r"\end{longtable}"]
    (RES / "table_types.tex").write_text("\n".join(tex) + "\n", encoding="utf-8")

    md.append("\n## Why runs were not accepted (reason of the run, by level)\n")
    for lv in LEVELS:
        rs = [r for r in sum([data.get((m, lv), []) for m in MAPS], []) if not r["accepted"]]
        if rs:
            md.append(f"* L{lv}: " + "; ".join(f"{k}: {v}" for k, v in collections.Counter(r["reason"] for r in rs).most_common()))
    md.append("\n## Zero-success cells\n")
    for lv in LEVELS:
        for m in MAPS:
            rs = data.get((m, lv), [])
            for t in TYPE_INFO:
                x = [r for r in rs if r["type"] == t]
                if x and not any(r["accepted"] for r in x):
                    md.append(f"* {m} L{lv} {t}: 0/{len(x)} accepted")
    (RES / "summary.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print("\n".join(md))


if __name__ == "__main__":
    main()
