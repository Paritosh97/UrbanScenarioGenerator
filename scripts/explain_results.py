r"""Write paper/results/L2_RESULTS_EXPLAINED.md: every prompt of the Sophia Antipolis evaluation with its expected axes and, run by run,
what the model produced and why a run was or was not adherent / solvable.

usage: python scripts/explain_results.py [results.jsonl] [prompts.json] [out.md]
"""
from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from usg.spec.axes import AXES, AXIS_DEFAULTS                                   # noqa: E402

res = Path(sys.argv[1] if len(sys.argv) > 1 else ROOT.parent / "paper" / "results" / "sophia_l2.jsonl")
prm = Path(sys.argv[2] if len(sys.argv) > 2 else ROOT / "eval" / "prompts_sophia.json")
out = Path(sys.argv[3] if len(sys.argv) > 3 else ROOT.parent / "paper" / "results" / "L2_RESULTS_EXPLAINED.md")

prompts = json.loads(prm.read_text(encoding="utf-8"))["prompts"]
runs = [json.loads(line) for line in res.read_text(encoding="utf-8").splitlines() if line.strip()]
runs = [r for r in runs if str(r["level"]) == "2"]
by = defaultdict(list)
for r in runs:
    by[r["id"]].append(r)
TYPES = ["ptp_env", "ptp_road", "cpath", "env_con", "dyn_nav", "dep_comp", "indep_comp", "mixed"]

HEAD = """# L2 results on the Sophia Antipolis map, explained

Data: `sophia_l2.jsonl` (75 runs = 25 prompts x 3 repetitions, model Qwen3.5-4B Q4_K_M, temperature 0.2, context 24576). Generated by `usg/scripts/explain_results.py`.
Map: Sophia Antipolis / Biot (Open Location Code 8FM9J389+G7), bbox S 43.61225, W 7.06263, N 43.62025, E 7.07363. Prompts: `usg/eval/prompts_sophia.json`.

## How each column is computed (code: `usg/scripts/benchmark.py`, function `score`)
Every denominator is ALL runs of the type (failed runs count as failures). 9 runs per type; `mixed` has 4 prompts, so 12.

**Accepted.** The run ended with a scenario that passed the validator (map rules, request grounding, rules derived from the formulas, nominal-walker check of safety rules).

**First try.** Accepted AND exactly 1 script submission AND at most 1 specification submission (the first specification was accepted and the first script was accepted).

**Submissions / run.** Mean number of `submit_script` calls over all runs (rejected ones count; a run that failed before ever submitting a script counts 0).

**Adherent.** Two checks, both must hold.
1. *Axes.* The constraint axes are READ OFF the finished formulas (`usg/src/usg/spec/axes.py`), not off what the model said:
   * `surface`: where the goal zone stands: centre on the road surface -> road; on a crosswalk or a crossing rectangle -> crossing; otherwise walkable.
   * `path`: corridor if any `near_path` or `on_surface` atom occurs in goal or safety rules (the `stay_on`, `stay_near_path` library rules expand to these); else free.
   * `static`: obstacles if a `dist_ge` atom (keep clear) refers to a NON-moving entity (parked car); else none.
   * `dynamic`: movers if a `dist_ge` atom refers to a moving entity (a driving vehicle); else none.
   * `signal`: obeyed if a `signal_is` atom occurs; else none.
   * `composition`: single (one task), ordered (several tasks run one after the other) or unordered (several tasks in parallel).
   The prompt lists the axes it expects. Every axis NOT listed must stay at its default (path free, static none, dynamic none, signal none, composition single), so an extra
   constraint counts against adherence. The `surface` axis is the exception: it is only checked when the prompt lists it.
2. *Atoms.* Only some prompts require operators (here: the two `mixed` prompts that ask to look at something need a `look_at` atom somewhere). The check passes if at least one is present;
   it passes automatically for prompts that list none.
Adherence is judged on constraint axes only. It does not judge the quality of the instruction text.

**Solvable.** After acceptance a *nominal walker* is simulated (walks the planned route at an ordinary pace, waits for green, keeps its gaze on look targets). The interval monitor evaluates
the goal and safety formulas of every task on that walk. Solvable = every task comes out satisfied. A run that was not accepted counts as not solvable.
Accepted and solvable can differ: the validator rejects a scenario if the nominal walk breaks a SAFETY rule written by the model (error); it only WARNS if the walk does not reach the goal.
(The run records keep the yes/no result of the nominal walk, not the margins, so the reason for a "not solvable" run is not stored.)

In the per-run tables: `sub` = script submissions / specification submissions; `axes` lists the axes that differ from the default (`-` = all default);
`why not adherent` lists each mismatch as axis: got vs expected.
"""


def diff(rec: dict, exp: dict) -> list[str]:
    ax = rec.get("axes") or {}
    wants = exp.get("axes", {})
    bad = []
    for a in AXES:
        if a in wants:
            if ax.get(a) != wants[a]:
                bad.append(f"{a}: {ax.get(a)} vs expected {wants[a]}")
        elif a != "surface" and ax.get(a) != AXIS_DEFAULTS[a]:
            bad.append(f"{a}: {ax.get(a)} (not asked, default is {AXIS_DEFAULTS[a]})")
    want_atoms = exp.get("atoms", [])
    if want_atoms and not any(o in (rec.get("ops") or []) for o in want_atoms):
        bad.append("no " + "/".join(want_atoms) + " atom")
    return bad


L = [HEAD]
for ty in TYPES:
    ps = [p for p in prompts if p["type"] == ty]
    if not ps:
        continue
    L.append(f"\n## {ty}\n")
    for p in ps:
        L.append(f"### `{p['id']}`\n**Prompt:** {p['text']}  \n**Expected:** axes {json.dumps(p['expect'].get('axes', {}))}"
                 + (f", at least one atom of {p['expect']['atoms']}" if p["expect"].get("atoms") else "")
                 + "; every other axis at its default.\n")
        L.append("| rep | accepted | sub | first try | axes of the scenario | adherent | why not adherent | solvable | why not accepted |")
        L.append("|---|---|---|---|---|---|---|---|---|")
        for r in sorted(by[p["id"]], key=lambda x: x.get("rep", 0)):
            ax = r.get("axes") or {}
            nd = ", ".join(f"{k}={v}" for k, v in ax.items() if v != AXIS_DEFAULTS[k]) or "-"
            if not r["accepted"]:
                nd = "(none: not accepted)"
                why = ""
                reason = r.get("reason", "").replace("|", "/")[:90]
            else:
                why = "; ".join(diff(r, p["expect"])) if not r["adherent"] else ""
                reason = ""
            L.append(f"| {r.get('rep', 0) + 1} | {'yes' if r['accepted'] else 'no'} | {r['attempts']}/{r['spec_attempts']} | {'yes' if r['first_try'] else 'no'} | {nd} | "
                     f"{'yes' if r['adherent'] else 'no'} | {why} | {'yes' if r['nominal_ok'] else 'no'} | {reason} |")
        L.append("")
out.write_text("\n".join(L) + "\n", encoding="utf-8")
print("wrote", out, len(runs), "runs")
